// Generates a ball-pit ball — `node tools/make-ball-model.mjs`: a light
// physics ball in the inflatable vinyl (materials/melon_racer/surfaces/
// inflatable.vmat from make-inflatable.mjs — run that first), white, so each
// placed prop_physics gets its color from its render color. Writes
//   models/melon_racer/ball.obj   render mesh: an icosphere, SUBDIVISIONS times
//                                 subdivided (20 · 4^n triangles), smooth normals
//   models/melon_racer/ball.vmdl  ModelDoc: that mesh, a sphere primitive for
//                                 collision (cheaper than any mesh), MASS_KG
// Compile the .vmdl with resourcecompiler (see the end of the output).
// Origin in the ball's center.
import { WriteAddonFile } from "./model.mjs";

const RADIUS = 10; // units — a bit bigger than the melon (~7)
const SUBDIVISIONS = 2; // 320 triangles: round at play distance, cheap with many balls
const MASS_KG = 0.05; // 50 g, very light: a melon shoves it out of the way
const LINEAR_DAMPING = 0.2; // a little air drag, so pushed balls don't roll on forever
const ANGULAR_DAMPING = 0.4;
const SURFACE_PROP = "rubber"; // bouncy, soft impact sounds
const UV_TILE = 64; // units one repeat of the vinyl's roughness covers
const MODEL_DIR = "models/melon_racer";
const NAME = "ball";
const MATERIAL = "materials/melon_racer/surfaces/inflatable.vmat";
const GENERATOR = "tools/make-ball-model.mjs";

// --- icosphere ---
const t = (1 + Math.sqrt(5)) / 2;
let verts = [
    [-1, t, 0], [1, t, 0], [-1, -t, 0], [1, -t, 0],
    [0, -1, t], [0, 1, t], [0, -1, -t], [0, 1, -t],
    [t, 0, -1], [t, 0, 1], [-t, 0, -1], [-t, 0, 1],
].map(Normalize);
let faces = [
    [0, 11, 5], [0, 5, 1], [0, 1, 7], [0, 7, 10], [0, 10, 11],
    [1, 5, 9], [5, 11, 4], [11, 10, 2], [10, 7, 6], [7, 1, 8],
    [3, 9, 4], [3, 4, 2], [3, 2, 6], [3, 6, 8], [3, 8, 9],
    [4, 9, 5], [2, 4, 11], [6, 2, 10], [8, 6, 7], [9, 8, 1],
];

function Normalize(p) {
    const len = Math.hypot(...p);
    return p.map(c => c / len);
}

for (let s = 0; s < SUBDIVISIONS; s++) {
    const midpoints = new Map();
    const Mid = (a, b) => {
        const key = a < b ? `${a},${b}` : `${b},${a}`;
        if (!midpoints.has(key)) {
            verts.push(Normalize(verts[a].map((c, i) => (c + verts[b][i]) / 2)));
            midpoints.set(key, verts.length - 1);
        }
        return midpoints.get(key);
    };
    faces = faces.flatMap(([a, b, c]) => {
        const ab = Mid(a, b), bc = Mid(b, c), ca = Mid(c, a);
        return [[a, ab, ca], [b, bc, ab], [c, ca, bc], [ab, bc, ca]];
    });
}

// --- .obj (ModelDoc reads Y up: Source (x, y, z) is written as (y, z, x), as in model.mjs ObjText) ---
const fmt = n => (Math.abs(n) < 1e-9 ? 0 : n).toFixed(5);
const Swap = ([x, y, z]) => [y, z, x];
const obj = [
    `# AUTO-GENERATED by ${GENERATOR}`,
    ...verts.map(p => `v ${Swap(p.map(c => c * RADIUS)).map(fmt).join(" ")}`),
    // No seam to cut: the vinyl's roughness only varies faintly, so a plain
    // projection of the surface is enough.
    ...verts.map(([x, y, z]) => `vt ${fmt(((x + y) * RADIUS) / UV_TILE)} ${fmt((z * RADIUS) / UV_TILE)}`),
    ...verts.map(p => `vn ${Swap(p).map(fmt).join(" ")}`),
    `usemtl ${NAME}_vinyl`,
    // Counter-clockwise seen from outside, like Mesh; indices are 1-based and
    // the same for position, uv and normal.
    ...faces.map(f => `f ${f.map(i => `${i + 1}/${i + 1}/${i + 1}`).join(" ")}`),
    "",
].join("\n");

const vmdl = `<!-- kv3 encoding:text:version{e21c7f3c-8a33-41c5-9977-a76d3a32aa0d} format:modeldoc36:version{972dada4-b828-45a4-bb93-7795cf0585da} -->
{
	rootNode =
	{
		_class = "RootNode"
		children =
		[
			{
				_class = "MaterialGroupList"
				children =
				[
					{
						_class = "DefaultMaterialGroup"
						remaps =
						[
							{ from = "${NAME}_vinyl.vmat" to = "${MATERIAL}" },
							{ from = "${NAME}_vinyl" to = "${MATERIAL}" },
						]
						use_global_default = false
						global_default_material = ""
					},
				]
			},
			{
				_class = "RenderMeshList"
				children =
				[
					{
						_class = "RenderMeshFile"
						filename = "${MODEL_DIR}/${NAME}.obj"
						import_translation = [ 0.0, 0.0, 0.0 ]
						import_rotation = [ 0.0, 0.0, 0.0 ]
						import_scale = 1.0
						align_origin_x_type = "None"
						align_origin_y_type = "None"
						align_origin_z_type = "None"
						parent_bone = ""
						import_filter =
						{
							exclude_by_default = false
							exception_list = [  ]
						}
					},
				]
			},
			{
				_class = "PhysicsShapeList"
				children =
				[
					{
						_class = "PhysicsShapeSphere"
						parent_bone = ""
						surface_prop = "${SURFACE_PROP}"
						collision_tags = "solid"
						radius = ${RADIUS.toFixed(1)}
						center = [ 0.0, 0.0, 0.0 ]
					},
				]
			},
			{
				_class = "PhysicsBodyMarkupList"
				children =
				[
					{
						_class = "PhysicsBodyMarkup"
						target_body = ""
						mass_override = ${MASS_KG.toFixed(3)}
						inertia_scale = 1.0
						linear_damping = ${LINEAR_DAMPING.toFixed(2)}
						angular_damping = ${ANGULAR_DAMPING.toFixed(2)}
						use_mass_center_override = false
						mass_center_override = [ 0.0, 0.0, 0.0 ]
					},
				]
			},
		]
		model_archetype = ""
		primary_associated_entity = ""
		anim_graph_name = ""
		base_model_name = ""
	}
}
`;

WriteAddonFile(`${MODEL_DIR}/${NAME}.obj`, obj);
WriteAddonFile(`${MODEL_DIR}/${NAME}.vmdl`, vmdl);
console.log(`${faces.length} triangles, ${verts.length} vertices, radius ${RADIUS}, ${MASS_KG} kg`);
console.log(`compile: game/bin/win64/resourcecompiler.exe -game csgo -addon melon_racer -i "<content path>/${MODEL_DIR}/${NAME}.vmdl"`);
