// Data the script needs from the map but can't ask the engine for, read out
// of maps/melon_racer.vmap into a generated src/ file — run by build.mjs
// before bundling, so a Hammer edit reaches the script on the next build.
//
// cs_script has no API to read an entity's keyvalues or bounds, so:
//   src/melon_drive/dev/visibility-boxes.js  every info_visibility_box (prefabs
//       included, turned and scaled with them): its middle, its own axes in
//       the world and half its box_size along each — the drone's limits
//       (dev/free-look.js).
// Written only when it changed (`npm run watch` would rebuild on every write);
// `npm run watch` also rebuilds it on every Hammer save (WatchMapData).
// test/dev/drone-bounds.test.mjs fails while it's out of date.
//
// Usage: node build-map-data.mjs (or npm run build)

import { readFileSync, writeFileSync, watch } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { ReadVmapEntityTransforms } from "./test/helpers/vmap.mjs";

const rootDir = path.dirname(fileURLToPath(import.meta.url));
const VMAP = path.join(rootDir, "maps", "melon_racer.vmap");
export const VISIBILITY_BOXES_FILE = path.join(rootDir, "src", "melon_drive", "dev", "visibility-boxes.js");

const Round = (/** @type {number} */ v) => Math.round(v * 1000) / 1000 + 0; // + 0: no -0
const Vec = (/** @type {number[]} */ [x, y, z]) => ({ x: Round(x), y: Round(y), z: Round(z) });

/**
 * Every info_visibility_box in the map: `center` (its origin — box_size is
 * centered on it), `axes` (its own x, y, z in the world) and `half` (half the
 * box_size along each, scaled).
 * @param {string} vmap
 */
export function ReadVisibilityBoxes(vmap = VMAP) {
    return ReadVmapEntityTransforms(vmap)
        .filter((e) => e.classname === "info_visibility_box")
        .map((e) => {
            const size = String(e.box_size ?? "0 0 0").trim().split(/\s+/).map(Number);
            return {
                center: Vec(e.origin),
                axes: [0, 1, 2].map((j) => Vec(e.rotation.map((row) => row[j]))),
                half: [0, 1, 2].map((i) => Round((Math.abs(size[i] || 0) * Math.abs(e.scale[i])) / 2)),
                file: e.files.at(-1),
            };
        });
}

/** The generated file's text. @param {ReturnType<typeof ReadVisibilityBoxes>} boxes */
export function VisibilityBoxesText(boxes) {
    const rows = boxes.map(({ center, axes, half, file }) =>
        `    // ${file}\n    { center: ${JSON.stringify(center)}, axes: ${JSON.stringify(axes)}, half: ${JSON.stringify(half)} },`);
    return [
        "// AUTO-GENERATED by build-map-data.mjs (npm run build) from maps/melon_racer.vmap — don't hand-edit.",
        "// Every info_visibility_box: its middle, its own x/y/z axes in the world and",
        "// half its box_size along each. The free-look drone stays inside the one",
        "// it starts in (dev/free-look.js).",
        "/** @type {{ center: { x: number, y: number, z: number }, axes: { x: number, y: number, z: number }[], half: number[] }[]} */",
        "export const VISIBILITY_BOXES = [",
        ...rows,
        "];",
        "",
    ].join("\n").replace(/"(\w+)":/g, "$1: ");
}

/** Writes the generated file if it changed. */
export function BuildMapData() {
    const boxes = ReadVisibilityBoxes();
    const text = VisibilityBoxesText(boxes);
    let old = "";
    try {
        old = readFileSync(VISIBILITY_BOXES_FILE, "utf8");
    } catch {
        // not there yet
    }
    if (old.replace(/\r\n/g, "\n") !== text) {
        writeFileSync(VISIBILITY_BOXES_FILE, text);
        console.log(`wrote src/melon_drive/dev/visibility-boxes.js (${boxes.length} info_visibility_box)`);
    }
}

/**
 * For `npm run watch`: rebuilds the map data whenever Hammer saves a .vmap
 * (the map or a prefab) — the changed src/ file then sets off Rollup's own
 * rebuild. A save still being written fails to read; the next event retries.
 */
export function WatchMapData() {
    const mapsDir = path.join(rootDir, "maps");
    /** @type {NodeJS.Timeout | undefined} */
    let pending;
    watch(mapsDir, { recursive: true }, (_event, file) => {
        if (!file || !String(file).endsWith(".vmap")) {
            return;
        }
        clearTimeout(pending);
        pending = setTimeout(() => {
            try {
                BuildMapData();
            } catch (error) {
                console.error(`map data: couldn't read the map yet (${error.message}) — trying again on the next save`);
            }
        }, 1000);
    });
    console.log("map data: watching maps/**/*.vmap for Hammer saves...");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    BuildMapData();
}
